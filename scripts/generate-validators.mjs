/** 从已锁定的权威 Schema 生成静态校验器，渲染进程不执行动态代码。 */
import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const ajv = new Ajv2020({
  allErrors: true,
  strict: false,
  code: { source: true, esm: true },
});
const exports = {};
for (const [name, file] of [
  ["validateManifestV1", "module-manifest-v1.schema.json"],
  ["validateManifestV2", "module-manifest-v2.schema.json"],
  ["validateModuleV1", "module-v1.schema.json"],
  ["validateModuleV2", "module-v2.schema.json"],
  ["validateLorebook", "lorebook-v3.schema.json"],
]) {
  const schema = JSON.parse(
    readFileSync(path.join(root, "schemas/trpgmod", file), "utf8"),
  );
  ajv.addSchema(schema);
  exports[name] = schema.$id;
}
// AJV 的 standalone 输出对长度助手使用 CommonJS require；转换为静态 ESM 引用。
const code = standaloneCode(ajv, exports).replaceAll(
  'require("ajv/dist/runtime/ucs2length").default',
  "ucs2length",
);
const generated =
  '// Generated by scripts/generate-validators.mjs from locked schemas. Do not edit manually.\nimport * as ucs2lengthRuntime from "ajv/dist/runtime/ucs2length.js";\nconst ucs2length = typeof ucs2lengthRuntime.default === "function" ? ucs2lengthRuntime.default : ucs2lengthRuntime.default.default;\n' +
  code +
  "\n";
const output = path.join(root, "src/domain/generated/schema-validators.js");
if (process.argv.includes("--check")) {
  if (readFileSync(output, "utf8") !== generated)
    throw new Error("Static validators drifted: run npm run schema:generate");
  console.log("Verified static validators against all five locked schemas");
} else {
  mkdirSync(path.dirname(output), { recursive: true });
  writeFileSync(output, generated);
  console.log("Generated CSP-safe static validators");
}
